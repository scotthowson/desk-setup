#!/usr/bin/env python3
"""Build the manual PDFs from the chapter fragments.

    python3 manual/build.py              # all three PDFs into manual/build/ and manual/*.pdf
    python3 manual/build.py manual       # just the manual
    python3 manual/build.py --render     # also render every page to PNG (manual/build/png/) for inspection
    python3 manual/build.py manual --only=05,06 --tag=steel --render --dpi=60   # one author's chapters only, to build/manual-steel.pdf and png/manual-steel/

Layout rules: each chapter fragment in manual/src/chapters/NN-name.html is a sequence of
<section class="page" data-chapter="E" data-title="Steel rails">...</section> blocks. This script numbers
the pages, adds the running header and footer, builds the table of contents from each page that carries
data-toc="Title", and prints with headless Chrome. Figures are inline SVG (generated by the chapter's
figures script into manual/figures/ and inlined here when a page uses <img class="fig" src="../figures/x.svg">).
"""
import glob, os, re, subprocess, sys, shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src"); FIG = os.path.join(ROOT, "figures"); OUT = os.path.join(ROOT, "build")
CSS = open(os.path.join(SRC, "style.css")).read()
TITLE = "L-Shaped Corner Desk · Assembly Manual"


def inline_figures(html):
    def rep(m):
        src = m.group(1)
        path = os.path.normpath(os.path.join(SRC, "chapters", src)) if not os.path.isabs(src) else src
        if not os.path.exists(path):
            path = os.path.join(FIG, os.path.basename(src))
        if not os.path.exists(path):
            return f'<div class="warn"><span class="warn-icon">!</span><div><b>MISSING FIGURE</b><br>{src}</div></div>'
        svg = open(path).read()
        svg = re.sub(r"<\?xml[^>]*\?>", "", svg)
        extra = m.group(2) or ""
        if "class=" not in svg[:300]:
            svg = svg.replace("<svg ", '<svg class="fig" ', 1)
        if extra:
            svg = svg.replace("<svg ", f"<svg {extra} ", 1)
        return svg
    return re.sub(r'<img class="fig" src="([^"]+)"([^>]*)/?>', rep, html)


def collect(kind, only=None):
    pat = {"manual": "chapters/[0-9][0-9]-*.html", "templates": "templates/[0-9][0-9]-*.html", "checklist": "checklist/[0-9][0-9]-*.html"}[kind]
    files = sorted(glob.glob(os.path.join(SRC, pat)))
    if only:
        files = [f for f in files if os.path.basename(f)[:2] in only]
    pages = []
    for f in files:
        html = inline_figures(open(f).read())
        for m in re.finditer(r"<section class=\"page([^\"]*)\"([^>]*)>(.*?)</section>", html, re.S):
            cls, attrs, body = m.group(1), m.group(2), m.group(3)
            ch = re.search(r'data-chapter="([^"]*)"', attrs); ti = re.search(r'data-title="([^"]*)"', attrs); toc = re.search(r'data-toc="([^"]*)"', attrs)
            pages.append({"cls": cls, "chapter": ch.group(1) if ch else "", "title": ti.group(1) if ti else "", "toc": toc.group(1) if toc else None, "body": body, "file": os.path.basename(f)})
    return pages


def render_pages(pages, doc_title, with_toc=True, toc_after=1):
    # page numbers: cover is 1; TOC inserted after `toc_after` pages
    toc_entries = []
    n = 0
    numbered = []
    for i, p in enumerate(pages):
        n += 1
        if with_toc and i == toc_after:
            n += 1  # reserve the TOC page
        p["n"] = n
        numbered.append(p)
        if p["toc"]:
            toc_entries.append((p["chapter"], p["toc"], n))
    out = []
    for i, p in enumerate(numbered):
        if with_toc and i == toc_after:
            items = "".join(f'<li><span><b>{c}</b>&nbsp; {t}</span><span>{pg}</span></li>' for c, t, pg in toc_entries)
            out.append(f'<section class="page"><div class="header"><span>{doc_title}</span><span></span></div><h1>Contents</h1><ul class="toc">{items}</ul><div class="footer"><span>{doc_title}</span><span>{toc_after + 1}</span></div></section>')
        hdr = "" if "cover" in p["cls"] else f'<div class="header"><span>{doc_title}</span><span>{p["chapter"]} · {p["title"]}</span></div>'
        ftr = "" if "cover" in p["cls"] else f'<div class="footer"><span>{doc_title}</span><span>Page {p["n"]}</span></div>'
        out.append(f'<section class="page{p["cls"]}">{hdr}{p["body"]}{ftr}</section>')
    return "\n".join(out)


def build(kind, only=None, tag=""):
    pages = collect(kind, only)
    if not pages:
        print(f"[{kind}] no pages"); return None
    doc_title = {"manual": TITLE, "templates": "Drilling and Placement Templates", "checklist": "Assembly Verification Checklist"}[kind]
    body = render_pages(pages, doc_title, with_toc=(kind == "manual"))
    html = f'<!doctype html><html><head><meta charset="utf-8"><title>{doc_title}</title><style>{CSS}</style></head><body>{body}</body></html>'
    os.makedirs(OUT, exist_ok=True)
    suffix = f"-{tag}" if tag else ""
    hp = os.path.join(OUT, f"{kind}{suffix}.html"); open(hp, "w").write(html)
    pdf = os.path.join(OUT, f"{kind}{suffix}.pdf")
    subprocess.run(["google-chrome", "--headless=new", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer", f"--print-to-pdf={pdf}", hp], capture_output=True, timeout=300)
    name = {"manual": "IKEA-Style-Assembly-Manual.pdf", "templates": "Drilling-and-Placement-Templates.pdf", "checklist": "Assembly-Verification-Checklist.pdf"}[kind]
    if not tag and not only:
        shutil.copy(pdf, os.path.join(ROOT, name))
    info = subprocess.run(["pdfinfo", pdf], capture_output=True, text=True).stdout
    n = re.search(r"Pages:\s+(\d+)", info)
    print(f"[{kind}] {len(pages)} sections -> {name}: {n.group(1) if n else '?'} pages")
    return pdf


def render_png(pdf, kind, dpi=50, tag=""):
    d = os.path.join(OUT, "png", kind + (f"-{tag}" if tag else "")); os.makedirs(d, exist_ok=True)
    for f in glob.glob(os.path.join(d, "*.png")): os.remove(f)
    subprocess.run(["pdftoppm", "-r", str(dpi), "-png", pdf, os.path.join(d, "p")])
    print(f"[{kind}] pages rendered to {d}")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    kinds = args or ["manual", "templates", "checklist"]
    only = next((a.split("=")[1].split(",") for a in sys.argv if a.startswith("--only=")), None)
    tag = next((a.split("=")[1] for a in sys.argv if a.startswith("--tag=")), "")
    for k in kinds:
        pdf = build(k, only=only, tag=tag)
        if pdf and "--render" in sys.argv:
            render_png(pdf, k, dpi=int(next((a.split("=")[1] for a in sys.argv if a.startswith("--dpi=")), 50)), tag=tag)
